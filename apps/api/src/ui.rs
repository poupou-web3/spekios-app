const CSP: &str = "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' blob: https: http:; connect-src 'self'; font-src 'self'; frame-src 'none'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'";
fn asset(body: impl IntoResponse, content_type: &'static str) -> Response {
    cached(body, content_type, "no-store")
}
fn cached(body: impl IntoResponse, content_type: &'static str, cache: &'static str) -> Response {
    (
        [
            (header::CONTENT_TYPE, content_type),
            (header::CACHE_CONTROL, cache),
            (header::CONTENT_SECURITY_POLICY, CSP),
            (header::X_CONTENT_TYPE_OPTIONS, "nosniff"),
            (header::REFERRER_POLICY, "no-referrer"),
        ],
        body,
    )
        .into_response()
}
