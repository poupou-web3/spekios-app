/// A closed embedded asset list generated by build.rs: this handler never reads request paths from disk.
/// `app/` is the workspace, `ui/` the shared kit, and `cli/` public CLI downloads. The back office is not embedded.
/// Pages reference `/assets/<ASSET_VERSION>/...`. Those URLs never change content, so browsers keep them;
/// unversioned paths (and a previous build's version) still answer, uncached.
pub async fn asset_file(Path(path): Path<String>) -> Response {
    let (path, cache) = match path.split_once('/') {
        Some((version, rest)) if version == ASSET_VERSION => (rest.to_string(), "public, max-age=31536000, immutable"),
        Some((version, rest)) if version.len() == 13 && version.starts_with('v') && version[1..].bytes().all(|b| b.is_ascii_hexdigit()) => (rest.to_string(), "no-store"),
        _ => (path, "no-store"),
    };
    if path == "cli/spekios-cli.tgz" {
        return asset(
            include_bytes!(concat!(env!("OUT_DIR"), "/spekios-cli.tgz")).as_slice(),
            "application/gzip",
        );
    }
    // Fonts are embedded too. Website favicons load from their own origins without a referrer.
    let font: Option<&'static [u8]> = match path.as_str() {
        "app/fonts/geist-400.ttf" => Some(include_bytes!("../../web/src/fonts/geist-400.ttf")),
        "app/fonts/geist-500.ttf" => Some(include_bytes!("../../web/src/fonts/geist-500.ttf")),
        "app/fonts/geist-600.ttf" => Some(include_bytes!("../../web/src/fonts/geist-600.ttf")),
        "app/fonts/geist-700.ttf" => Some(include_bytes!("../../web/src/fonts/geist-700.ttf")),
        "app/fonts/geist-mono-400.ttf" => Some(include_bytes!("../../web/src/fonts/geist-mono-400.ttf")),
        "app/fonts/geist-mono-500.ttf" => Some(include_bytes!("../../web/src/fonts/geist-mono-500.ttf")),
        "app/fonts/instrument-serif-400.ttf" => Some(include_bytes!("../../web/src/fonts/instrument-serif-400.ttf")),
        "app/fonts/instrument-serif-400-italic.ttf" => Some(include_bytes!("../../web/src/fonts/instrument-serif-400-italic.ttf")),
        _ => None,
    };
    if let Some(body) = font {
        return cached(body, "font/ttf", cache);
    }
    match ASSETS.iter().find(|(name, _, _)| *name == path) {
        Some((_, content_type, body)) => cached(*body, content_type, cache),
        None => error(StatusCode::NOT_FOUND, "asset_not_found"),
    }
}

async fn bytes(state: &AppState, row: Value) -> Response {
    if row["status"] != "available" {
        return error(StatusCode::CONFLICT, "evidence_not_available");
    }
    let Some(gateway) = &state.gateway else {
        return error(StatusCode::SERVICE_UNAVAILABLE, "evidence_unavailable");
    };
    let (Some(key), Some(sha), Some(length)) = (
        row["object_key"].as_str(),
        row["sha256"].as_str(),
        row["byte_length"].as_u64(),
    ) else {
        return error(StatusCode::CONFLICT, "incomplete_evidence");
    };
    match gateway.evidence_bytes(key, sha, length).await {
        Ok(body) => (
            [
                (
                    header::CONTENT_TYPE,
                    if key.ends_with(".png") {
                        "image/png"
                    } else {
                        "application/json"
                    },
                ),
                (header::X_CONTENT_TYPE_OPTIONS, "nosniff"),
                (header::CACHE_CONTROL, "no-store"),
            ],
            body,
        )
            .into_response(),
        Err(code) => error(StatusCode::BAD_GATEWAY, code),
    }
}
pub async fn capture_image(ScopedState(state): ScopedState, Path(id): Path<Uuid>) -> Response {
    match query(&state,"SELECT to_jsonb(c) FROM runtime_captures c JOIN runtime_runs r USING(run_id) WHERE c.capture_id=$1 AND r.workspace_id=$2",&[&id,&state.principal.workspace_id]).await {
        Ok(Some(row))=>bytes(&state,row).await,Ok(None)=>error(StatusCode::NOT_FOUND,"capture_not_found"),Err(r)=>r,
    }
}
